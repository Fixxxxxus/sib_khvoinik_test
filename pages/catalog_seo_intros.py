SEO_INTROS: dict[str, str] = {slug: _nbsp(html) for slug, html in _RAW.items()}


def _db_seo_intro(slug: str) -> str:
    try:
        from pages.models import CatalogCategory, CatalogSubcategory

        for model in (CatalogCategory, CatalogSubcategory):
            value = model.objects.filter(slug=slug).values_list("seo_intro", flat=True).first()
            if value and value.strip():
                return value
    except Exception:  # pragma: no cover - нет таблиц/миграций, работаем на статике
        pass
    return ""


def seo_intro_for_slug(slug: str) -> str:
    """HTML интро для раздела: БД (если каталог из БД) -> SEO_INTROS -> пусто."""
    html = ""
    if getattr(settings, "USE_DATABASE_CATALOG", False):
        html = _db_seo_intro(slug)
    if not html:
        html = SEO_INTROS.get(slug, "")
    return style_links(html) if html else ""
