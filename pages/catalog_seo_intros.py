LINK_CLASS = "font-semibold text-brand underline underline-offset-2 hover:text-brand2"

_NBSP_WORDS = (
    "в", "во", "с", "со", "к", "ко", "и", "а", "о", "об", "у", "на", "по", "до", "из",
    "от", "не", "за", "но", "же", "ли", "для", "без", "при", "под", "над",
)
_NBSP_RE = re.compile(
    r"(?<![\w-])(" + "|".join(_NBSP_WORDS) + r") (?=[\w«<])",
    re.IGNORECASE,
)
_BARE_LINK_RE = re.compile(r"<a(?![^>]*\bclass=)(\s[^>]*)?>", re.IGNORECASE)


def _nbsp(html: str) -> str:
    """Неразрывный пробел после коротких предлогов и союзов (типографика rustxt)."""
    return _NBSP_RE.sub(lambda m: m.group(1) + " ", html)


def style_links(html: str) -> str:
    """Добавляет фирменный стиль ссылкам без class: preflight Tailwind их обесцвечивает."""
    return _BARE_LINK_RE.sub(lambda m: f'<a class="{LINK_CLASS}"{m.group(1) or ""}>', html)


